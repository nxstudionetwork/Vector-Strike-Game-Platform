/**
 * Maps icon keys stored in the database (categories, achievements) to icons.
 * Unknown keys fall back to a neutral glyph so new content never breaks the UI.
 */
import {
  Atom,
  Award,
  Brain,
  Calendar,
  Code2,
  Coins,
  Compass,
  Crown,
  Flag,
  FlaskConical,
  Flame,
  Gem,
  Globe2,
  Landmark,
  Languages,
  Layers,
  Leaf,
  Lock,
  Medal,
  Mountain,
  Palette,
  Puzzle,
  Rocket,
  Shield,
  Sigma,
  Sparkles,
  Star,
  Swords,
  Target,
  TrendingUp,
  Trophy,
  Zap,
  type LucideIcon,
  type LucideProps,
} from 'lucide-react'

const ICONS: Record<string, LucideIcon> = {
  atom: Atom,
  award: Award,
  brain: Brain,
  calendar: Calendar,
  code: Code2,
  coins: Coins,
  compass: Compass,
  crown: Crown,
  flag: Flag,
  flask: FlaskConical,
  flame: Flame,
  gem: Gem,
  globe: Globe2,
  landmark: Landmark,
  languages: Languages,
  layers: Layers,
  leaf: Leaf,
  lock: Lock,
  medal: Medal,
  mountain: Mountain,
  palette: Palette,
  puzzle: Puzzle,
  rocket: Rocket,
  shield: Shield,
  sigma: Sigma,
  sparkles: Sparkles,
  star: Star,
  swords: Swords,
  target: Target,
  'trending-up': TrendingUp,
  trophy: Trophy,
  zap: Zap,
}

export function Icon({ name, ...props }: { name: string } & LucideProps) {
  const Component = ICONS[name] ?? Sparkles
  return <Component aria-hidden="true" {...props} />
}
